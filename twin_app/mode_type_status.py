from __future__ import annotations

"""Minimal, material-independent provenance contract for displayed twin types.

Do not reinterpret an unclassified rank-one branch as Type I/II/Compound.
Accept direct cross-locks and *proved parent-symmetry transport* distinctly;
the latter is not a second independent direct classification of the target.
"""


def supported_classical_type(classification: object, status: object) -> bool:
    if str(classification) not in ("Type I", "Type II", "Compound"):
        return False
    value = str(status).strip().lower()
    if value.startswith("cross-locked:"):
        return True
    # Generated by scientific_engine -> symmetry_completion from a direct
    # cross-lock witness with indexed parent-group transport and residuals.
    # "cross-locked" anywhere in a diagnostic or rejection is NOT sufficient.
    return (
        value.startswith("symmetry-transported from directly cross-locked ")
        and "; g-index " in value
        and "; ordered stretch and physical rank-one tensor residuals " in value
        and value.endswith(
            "this is not an independent discrete cross-lock for the target pair"
        )
    )
