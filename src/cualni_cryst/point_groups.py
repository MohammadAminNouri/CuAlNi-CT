from __future__ import annotations

"""Conventional crystallographic point-group registry.

The registry provides exact direct-coordinate symmetry matrices for all 32
crystallographic point groups in standard conventional settings.

Important
---------
The matrices act on crystallographic direct coordinates, not on an assumed
orthonormal Cartesian basis. ProjectState validation independently checks

    G.T @ M @ G == M

against the user's actual lattice metric. Therefore an incompatible cell/point
group combination fails loudly instead of being silently coerced.

Trigonal groups use hexagonal axes in the built-in registry. Rhombohedral-axis
users can supply explicit symmetry matrices through project JSON.
"""

import re
from dataclasses import dataclass

import numpy as np
import sympy as sp

MatrixKey = tuple[sp.Expr, ...]


def _key(matrix: sp.Matrix) -> MatrixKey:
    return tuple(sp.simplify(value) for value in list(sp.Matrix(matrix)))


def _sort_key(matrix: sp.Matrix) -> tuple[str, ...]:
    return tuple(str(sp.simplify(value)) for value in list(matrix))


def _closure(generators: tuple[sp.Matrix, ...]) -> tuple[sp.Matrix, ...]:
    """Exact finite matrix group generated by `generators`."""
    identity = sp.eye(3)
    found: dict[MatrixKey, sp.Matrix] = {_key(identity): identity}
    generators = tuple(sp.Matrix(generator) for generator in generators)

    changed = True
    while changed:
        changed = False
        current = tuple(found.values())
        for left in current:
            for right in (*generators, *current):
                product = sp.simplify(left * right)
                key = _key(product)
                if key not in found:
                    found[key] = product
                    changed = True
                    if len(found) > 48:
                        raise AssertionError(
                            "Crystallographic point group unexpectedly exceeded order 48."
                        )

    matrices = sorted(found.values(), key=_sort_key)
    matrices.remove(identity)
    return (identity, *matrices)


I = sp.eye(3)
INV = -I

