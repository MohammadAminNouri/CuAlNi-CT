# Cubic cyclic 3-fold about [111].
C3_111 = sp.Matrix(
    [
        [0, 0, 1],
        [1, 0, 0],
        [0, 1, 0],
    ]
)

M_XY_SWAP = sp.Matrix(
    [
        [0, 1, 0],
        [1, 0, 0],
        [0, 0, 1],
    ]
)


@dataclass(frozen=True)
class PointGroupDefinition:
    symbol: str
    crystal_family: str
    conventional_setting: str
    expected_order: int
    generators: tuple[sp.Matrix, ...]
    aliases: tuple[str, ...] = ()

    def operations(self) -> tuple[sp.Matrix, ...]:
        operations = _closure(self.generators)
        if len(operations) != self.expected_order:
            raise AssertionError(
                f"{self.symbol}: expected order {self.expected_order}, "
                f"generated {len(operations)}."
            )
        return operations


