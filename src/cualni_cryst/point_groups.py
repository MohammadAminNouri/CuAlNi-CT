def _normalize_symbol(symbol: str) -> str:
    text = symbol.strip().lower()
    text = text.replace("−", "-").replace("–", "-").replace("—", "-")
    text = text.replace(" ", "").replace("_", "")
    text = re.sub(r"[()]", "", text)
    return text


_BY_CANONICAL = {definition.symbol: definition for definition in _DEFINITIONS}
_BY_ALIAS: dict[str, PointGroupDefinition] = {}

for definition in _DEFINITIONS:
    candidates = (definition.symbol, *definition.aliases)
    for candidate in candidates:
        normalized = _normalize_symbol(candidate)
        existing = _BY_ALIAS.get(normalized)
        if existing is not None and existing.symbol != definition.symbol:
            raise AssertionError(
                f"Ambiguous point-group alias {candidate!r}: "
                f"{existing.symbol} vs {definition.symbol}."
            )
        _BY_ALIAS[normalized] = definition


def point_group_definitions() -> tuple[PointGroupDefinition, ...]:
    return _DEFINITIONS


def resolve_point_group(symbol: str) -> PointGroupDefinition:
    normalized = _normalize_symbol(symbol)
    definition = _BY_ALIAS.get(normalized)
    if definition is None:
        available = ", ".join(item.symbol for item in _DEFINITIONS)
        raise ValueError(
            f"Unknown crystallographic point group {symbol!r}. "
            f"Supported conventional groups: {available}. "
            "For a nonstandard setting, provide explicit symmetry matrices."
        )
    return definition


def point_group_operations(symbol: str) -> tuple[sp.Matrix, ...]:
    return resolve_point_group(symbol).operations()


def point_group_table() -> tuple[dict[str, object], ...]:
    rows = []
    for definition in _DEFINITIONS:
        rows.append(
            {
                "symbol": definition.symbol,
                "crystal_family": definition.crystal_family,
                "conventional_setting": definition.conventional_setting,
                "order": definition.expected_order,
                "aliases": list(definition.aliases),
            }
        )
    return tuple(rows)


def metric_preservation_residual(
    operations: tuple[sp.Matrix, ...],
    metric: np.ndarray,
) -> float:
    M = np.asarray(metric, dtype=float).reshape(3, 3)
    scale = max(float(np.linalg.norm(M)), 1.0)
    worst = 0.0
    for operation in operations:
        G = np.asarray(operation, dtype=float)
        residual = float(np.linalg.norm(G.T @ M @ G - M) / scale)
        worst = max(worst, residual)
    return worst
